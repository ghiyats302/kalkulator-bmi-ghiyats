    private void jToggleButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton1ActionPerformed
    double iTinggi = Double.parseDouble(jTextTinggi.getText());
    double iBerat = Double.parseDouble(jTextBerat.getText());
    double iBMI = iBerat / (iTinggi * iTinggi);
    
    String Calc_BMI = String.format("%.2f", iBMI);
    jlblBMI.setText (Calc_BMI);
    
    if (iBMI <= 24.9) {
        jlblBMI.setOpaque(true);
        jlblBMI.setBackground(Color.BLUE);
        jlblBMI.setForeground(Color.WHITE); 
    } else if (iBMI <= 29.9) {
        jlblBMI.setOpaque(true);
        jlblBMI.setBackground(Color.YELLOW);
        jlblBMI.setForeground(Color.BLACK);
    } else if (iBMI <= 34.9) {
        jlblBMI.setOpaque(true);
        jlblBMI.setBackground(Color.PINK);
        jlblBMI.setForeground(Color.BLACK);
    } else if (iBMI <= 39.9) {
        jlblBMI.setOpaque(true);
        jlblBMI.setBackground(Color.ORANGE);
        jlblBMI.setForeground(Color.BLACK);
    } else {
        jlblBMI.setOpaque(true);
        jlblBMI.setBackground(Color.RED);
        jlblBMI.setForeground(Color.WHITE);
    }
    }//GEN-LAST:event_jToggleButton1ActionPerformed

